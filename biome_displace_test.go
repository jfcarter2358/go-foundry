// TestResolvedSlopeDefaultsGateNothing pins the deliberate choice that an
// unset slope pair restricts nothing, for every kind: the sliders are opt-in,
// so painting a sector behaves exactly as it did before slope gating existed.
// An earlier revision defaulted Rock to a 20-degree *minimum*, which deleted
// Rock from every flat floor once gating started applying to ordinary sloped
// and terrain floors instead of only procedurally-displaced ones.
func TestResolvedSlopeDefaultsGateNothing(t *testing.T) {
	for _, k := range allBiomeKinds {
		if got := resolvedMinSlope(k, 0); got != 0 {
			t.Errorf("resolvedMinSlope(kind %d, 0) = %v, want 0 (unset must not restrict)", k, got)
		}
		if got := resolvedMaxSlope(k, 0); got != 90 {
			t.Errorf("resolvedMaxSlope(kind %d, 0) = %v, want 90 (unset must not restrict)", k, got)
		}
		// The full range must cover every possible surface orientation.
		for deg := 0.0; deg <= 90.0; deg += 7.5 {
			if c := slopeCoverage(k, normalAtAngle(deg), 0, 0); c != 1 {
				t.Errorf("kind %d with an unset slope range has coverage %v at %.1f degrees, want 1", k, c, deg)
			}
		}
	}

	// Explicit values win over the defaults.
	if got := resolvedMinSlope(BiomeRock, 12); got != 12 {
		t.Errorf("resolvedMinSlope(Rock, 12) = %v, want 12", got)
	}
	if got := resolvedMaxSlope(BiomeGrass, 55); got != 55 {
		t.Errorf("resolvedMaxSlope(Grass, 55) = %v, want 55", got)
	}
}

// normalAtAngle returns a unit normal tilted `deg` degrees away from world-up.
func normalAtAngle(deg float64) mgl32.Vec3 {
	r := deg * math.Pi / 180
	return mgl32.Vec3{float32(math.Sin(r)), float32(math.Cos(r)), 0}
}

// TestSlopeCoverageGatesByAngle checks the core gating behavior for an
// authored below-an-angle range: flat ground is fully covered, a wall-steep
// face fully excluded, and coverage is monotonically non-increasing as the
// surface tilts (so the biome thins out toward the limit rather than popping).
func TestSlopeCoverageGatesByAngle(t *testing.T) {
	const maxA = float32(40)
	if c := slopeCoverage(BiomeGrass, mgl32.Vec3{0, 1, 0}, 0, maxA); c != 1 {
		t.Errorf("Grass coverage on flat ground = %v, want 1", c)
	}
	if c := slopeCoverage(BiomeGrass, normalAtAngle(85), 0, maxA); c != 0 {
		t.Errorf("Grass coverage on an 85-degree face = %v, want 0", c)
	}

	prev := float32(1)
	for deg := 0.0; deg <= 90.0; deg += 2.5 {
		c := slopeCoverage(BiomeGrass, normalAtAngle(deg), 0, maxA)
		if c < 0 || c > 1 {
			t.Fatalf("coverage %v at %.1f degrees outside [0,1]", c, deg)
		}
		if c > prev+1e-6 {
			t.Fatalf("coverage rose from %v to %v at %.1f degrees — must be non-increasing for a max-only range", prev, c, deg)
		}
		prev = c
	}
}

// TestSlopeCoverageMinAngleExcludesFlat checks the min-angle half of the range
// works: authoring a minimum keeps a kind off flat ground and onto steeper
// faces, which is how Grass and Rock painted over the same outcrop can be made
// to zone themselves by slope. Opt-in — see
// TestResolvedSlopeDefaultsGateNothing for the defaults.
func TestSlopeCoverageMinAngleExcludesFlat(t *testing.T) {
	const minA = float32(20)
	flat := slopeCoverage(BiomeRock, mgl32.Vec3{0, 1, 0}, minA, 90)
	if flat != 0 {
		t.Errorf("Rock coverage on flat ground with a %v-degree minimum = %v, want 0", minA, flat)
	}
	steep := slopeCoverage(BiomeRock, normalAtAngle(float64(minA)+20), minA, 90)
	if steep != 1 {
		t.Errorf("Rock coverage well above the minimum = %v, want 1", steep)
	}
	if vertical := slopeCoverage(BiomeRock, normalAtAngle(85), minA, 90); vertical != 1 {
		t.Errorf("Rock coverage on a near-vertical face = %v, want 1", vertical)
	}
}

// TestSlopeCoverageNormalizesInput is the regression test for the bug behind
// "changing the slope angles doesn't do anything". InterpolateSurfaceHeight
// returns collision.go's raw triangleNormal — a cross product whose length
// scales with triangle area, e.g. (0,256,-128) for a 16x16 floor quad. Reading
// .Y off that and clamping into acos's domain pinned every structural normal
// at 0 degrees, so gating thought every sloped floor was level. slopeCoverage
// must normalize, so a scaled normal gates identically to its unit form.
func TestSlopeCoverageNormalizesInput(t *testing.T) {
	for _, deg := range []float64{0, 20, 26.57, 45, 70, 89} {
		unit := normalAtAngle(deg)
		for _, scale := range []float32{0.001, 1, 128, 286.22, 10000} {
			scaled := unit.Mul(scale)
			for _, r := range [][2]float32{{0, 30}, {0, 60}, {20, 90}, {30, 60}} {
				want := slopeCoverage(BiomeMoss, unit, r[0], r[1])
				got := slopeCoverage(BiomeMoss, scaled, r[0], r[1])
				if abs32(got-want) > 1e-5 {
					t.Fatalf("normal at %.2f degrees scaled by %v gates differently: got %v, want %v (range %v..%v)",
						deg, scale, got, want, r[0], r[1])
				}
			}
		}
	}

	// The specific shape the bug produced: a ~26.57-degree floor quad normal.
	raw := mgl32.Vec3{0, 256, -128}
	if c := slopeCoverage(BiomeMoss, raw, 0, 10); c != 0 {
		t.Errorf("a raw (0,256,-128) normal (~26.6 degrees) with a 10-degree ceiling has coverage %v, want 0", c)
	}

	// A degenerate normal must not exclude everything (or a zero-area triangle
	// would silently erase the biome there).
	if c := slopeCoverage(BiomeMoss, mgl32.Vec3{}, 0, 10); c != 1 {
		t.Errorf("degenerate normal coverage = %v, want 1", c)
	}
}

// TestSlopeCoverageFeathersNotSteps checks the transition is a smooth ramp,
// not a hard cutoff: right at the limit angle coverage must be partial
// (strictly between 0 and 1), which is what keeps the painted area from
// ending in a visible ring.
func TestSlopeCoverageFeathersNotSteps(t *testing.T) {
	const maxA = float32(40)
	at := slopeCoverage(BiomeGrass, normalAtAngle(float64(maxA)), 0, maxA)
	if at <= 0 || at >= 1 {
		t.Fatalf("coverage exactly at the max angle = %v, want a partial value (feathered edge)", at)
	}
	inside := slopeCoverage(BiomeGrass, normalAtAngle(float64(maxA-slopeFeatherDegrees-1)), 0, maxA)
	outside := slopeCoverage(BiomeGrass, normalAtAngle(float64(maxA+slopeFeatherDegrees+1)), 0, maxA)
	if inside != 1 {
		t.Errorf("coverage well inside the range = %v, want 1", inside)
	}
	if outside != 0 {
		t.Errorf("coverage well outside the range = %v, want 0", outside)
	}
}

// TestSlopeCoverageExplicitRange checks an explicitly-authored range is what
// actually gates, not the kind's default — a band that excludes both flat and
// vertical, covering only the middle.
func TestSlopeCoverageExplicitRange(t *testing.T) {
	const minA, maxA = float32(30), float32(60)
	if c := slopeCoverage(BiomeGrass, mgl32.Vec3{0, 1, 0}, minA, maxA); c != 0 {
		t.Errorf("coverage on flat ground with a 30..60 band = %v, want 0", c)
	}
	if c := slopeCoverage(BiomeGrass, normalAtAngle(45), minA, maxA); c != 1 {
		t.Errorf("coverage at 45 degrees with a 30..60 band = %v, want 1", c)
	}
	if c := slopeCoverage(BiomeGrass, normalAtAngle(85), minA, maxA); c != 0 {
		t.Errorf("coverage at 85 degrees with a 30..60 band = %v, want 0", c)
	}
}

// flatFloorAt returns a level with one 16x16 sector whose floor sits level at
// the given height, with the given per-vertex Y offsets applied (nil = level).
// Offsets are index-aligned with PointIndices, so a pair of raised corners
// tilts the floor into a ramp — no terrain mode or detail spec involved.
func flatFloorAt(height float32, offsets []float32) *Level {
	return &Level{Chunks: []Chunk{{
		Points: []mgl32.Vec2{{-8, -8}, {8, -8}, {8, 8}, {-8, 8}},
		Sectors: []Sector{{
			ID:           "s0",
			PointIndices: []int{0, 1, 2, 3},
			Floor:        Floor{Enabled: true, Height: height, VertexOffsets: offsets},
		}},
	}}}
}

// TestBiomeSurfaceAtLevelFloorStaysFullyCovered is the regression guard for
// "adding slope gating must not thin out biomes on existing flat levels": with
// the shipped (unset) slope range, a level floor is fully covered for every
// following kind, and the height stays within the ground patch's own
// bias+noise of the structural floor — i.e. no displacement field is applied.
func TestBiomeSurfaceAtLevelFloorStaysFullyCovered(t *testing.T) {
	lvl := flatFloorAt(3, nil)

	for _, k := range []int32{BiomeGrass, BiomeRock, BiomeSand, BiomeMoss} {
		brush := defaultBiomeBrush(k) // unset slope range: must not restrict

		// Sand's patch amplitude is SandHeight, not GroundAmplitude.
		amp := brush.GroundAmplitude
		if k == BiomeSand {
			amp = brush.SandHeight * 1.15 // dunes + the ripple layer's 15% headroom
		}
		bound := groundPatchYBias + amp + 1e-4

		h, cov := biomeSurfaceAt(lvl, &brush, mgl32.Vec2{1, 2}, 0, 0)
		if abs32(h-3) > bound {
			t.Errorf("kind %d height over a level floor = %v, further than bias+amplitude (%v) from the floor at 3", k, h, bound)
		}
		if cov != 1 {
			t.Errorf("kind %d coverage over a level floor = %v, want 1 with the default slope range", k, cov)
		}
	}
}

// TestSlopeGatingAppliesToPlainSlopedFloor is the regression test for the
// reported bug: "changing the slope angles doesn't do anything". Coverage used
// to be computed only when the covering floor carried procedural displacement
// detail, so on a floor sloped by ordinary per-vertex offsets (or terrain mode
// — both come back through InterpolateSurfaceHeight with a real normal) the
// sliders were dead. This floor has NO detail spec at all: the gating has to
// come from the structural normal alone.
func TestSlopeGatingAppliesToPlainSlopedFloor(t *testing.T) {
	// Two corners raised by 8 over a 16-unit span — roughly a 26-degree ramp.
	lvl := flatFloorAt(0, []float32{0, 0, 8, 8})

	// Confirm the fixture really is sloped, or the rest proves nothing.
	_, n, sector := floorHeightNormalUnderLevel(lvl, 0, 0)
	if sector == nil {
		t.Fatal("fixture sector not found under (0,0)")
	}
	if sector.Floor.Detail.HasDisplace() {
		t.Fatal("fixture floor must have no displacement detail — that's the point of this test")
	}
	// Normalize before reading the angle: InterpolateSurfaceHeight's normal is a
	// raw cross product scaled by triangle area, not a unit vector.
	angle := float32(math.Acos(float64(clamp01(n.Normalize().Y())))) * 180 / math.Pi
	if angle < 10 {
		t.Fatalf("fixture floor is only %.1f degrees from level; expected a meaningful ramp", angle)
	}

	brush := defaultBiomeBrush(BiomeMoss)

	// Default (unset) range covers everything.
	if _, cov := biomeSurfaceAt(lvl, &brush, testSeed, 0, 0); cov != 1 {
		t.Errorf("coverage with the default range = %v, want 1", cov)
	}

	// A ceiling below the ramp's angle must exclude it outright...
	brush.MinSlopeAngle, brush.MaxSlopeAngle = 0, angle-slopeFeatherDegrees-2
	if _, cov := biomeSurfaceAt(lvl, &brush, testSeed, 0, 0); cov != 0 {
		t.Errorf("coverage with max angle below the ramp's %.1f degrees = %v, want 0 — the slope sliders are not reaching a plainly sloped floor", angle, cov)
	}

	// ...and a ceiling above it must admit it.
	brush.MinSlopeAngle, brush.MaxSlopeAngle = 0, angle+slopeFeatherDegrees+2
	if _, cov := biomeSurfaceAt(lvl, &brush, testSeed, 0, 0); cov != 1 {
		t.Errorf("coverage with max angle above the ramp's %.1f degrees = %v, want 1", angle, cov)
	}

	// A floor (minimum) above the ramp's angle must exclude it too.
	brush.MinSlopeAngle, brush.MaxSlopeAngle = angle+slopeFeatherDegrees+2, 90
	if _, cov := biomeSurfaceAt(lvl, &brush, testSeed, 0, 0); cov != 0 {
		t.Errorf("coverage with min angle above the ramp's %.1f degrees = %v, want 0", angle, cov)
	}
}

// TestRotateNormalBetween covers the frame composition used when a displaced
// face also sits on sloped/terrain ground: identity when the frames already
// agree, actually rotating otherwise, and always unit length.
func TestRotateNormalBetween(t *testing.T) {
	up := mgl32.Vec3{0, 1, 0}
	tilted := normalAtAngle(30)

	// Same frame: unchanged.
	if got := rotateNormalBetween(up, up, tilted); (got.Sub(tilted)).Len() > 1e-6 {
		t.Errorf("rotating between identical frames changed the normal: %v -> %v", tilted, got)
	}

	// up -> tilted applied to up should land on tilted.
	if got := rotateNormalBetween(up, tilted, up); (got.Sub(tilted)).Len() > 1e-5 {
		t.Errorf("rotateNormalBetween(up, tilted, up) = %v, want %v", got, tilted)
	}

	// Antiparallel frames flip.
	down := mgl32.Vec3{0, -1, 0}
	if got := rotateNormalBetween(up, down, up); (got.Sub(down)).Len() > 1e-5 {
		t.Errorf("antiparallel rotation of up = %v, want %v", got, down)
	}

	// Always unit length.
	for _, deg := range []float64{0, 15, 45, 75, 90} {
		got := rotateNormalBetween(up, normalAtAngle(deg), normalAtAngle(20))
		if l := got.Len(); abs32(l-1) > 1e-5 {
			t.Errorf("rotated normal at %.0f degrees has length %v, want 1", deg, l)
		}
	}
}

// TestBiomeSurfaceAtNoSector checks the open-ground fallback still works (no
// chunk/sector under the point) rather than panicking on a nil sector. The
// floor height there is 0, so the result is just the ground patch's own
// bias+noise about 0.
func TestBiomeSurfaceAtNoSector(t *testing.T) {
	lvl := &Level{}
	for _, k := range []int32{BiomeGrass, BiomeMoss, BiomeWater} {
		brush := defaultBiomeBrush(k)
		h, cov := biomeSurfaceAt(lvl, &brush, mgl32.Vec2{4, 5}, 5, 5)
		if bound := groundPatchYBias + brush.GroundAmplitude + 1e-4; abs32(h) > bound {
			t.Errorf("kind %d height over open ground = %v, want within %v of 0", k, h, bound)
		}
		if cov != 1 {
			t.Errorf("kind %d coverage over open ground = %v, want 1", k, cov)
		}
	}
}

// TestRawBiomeBrushMossYAMLRoundTrip pins the newly-persisted fields
// surviving a marshal/unmarshal cycle, and that all three stay absent from
// the output at their zero values (omitempty, so existing level files don't
// grow noise).
func TestRawBiomeBrushMossYAMLRoundTrip(t *testing.T) {
	rb := RawBiomeSector{
		ID:     "m0",
		Points: []Point{{X: 0, Y: 0}, {X: 1, Y: 0}, {X: 1, Y: 1}},
		Brush: RawBiomeBrush{
			Kind:          BiomeMoss,
			Density:       0.6,
			MossScatter:   true,
			MinSlopeAngle: 15,
			MaxSlopeAngle: 65,
		},
	}

	out, err := yaml.Marshal(rb)
	if err != nil {
		t.Fatalf("marshal: %v", err)
	}
	var got RawBiomeSector
	if err := yaml.Unmarshal(out, &got); err != nil {
		t.Fatalf("unmarshal: %v", err)
	}
	if !got.Brush.MossScatter {
		t.Error("MossScatter did not survive the round trip")
	}
	if got.Brush.MinSlopeAngle != 15 {
		t.Errorf("MinSlopeAngle round trip: got %v, want 15", got.Brush.MinSlopeAngle)
	}
	if got.Brush.MaxSlopeAngle != 65 {
		t.Errorf("MaxSlopeAngle round trip: got %v, want 65", got.Brush.MaxSlopeAngle)
	}

	zero, err := yaml.Marshal(RawBiomeSector{ID: "z", Brush: RawBiomeBrush{Kind: BiomeGrass}})
	if err != nil {
		t.Fatalf("marshal zero: %v", err)
	}
	for _, key := range []string{"moss_scatter", "min_slope_angle", "max_slope_angle"} {
		if containsSubstring(string(zero), key) {
			t.Errorf("zero-valued brush emitted %q — should be omitempty", key)
		}
	}
}

func containsSubstring(haystack, needle string) bool {
	for i := 0; i+len(needle) <= len(haystack); i++ {
		if haystack[i:i+len(needle)] == needle {
			return true
		}
	}
	return false
}

// TestBiomeSeedChangesWithSlopeFields extends the existing biomeSeed
// regression coverage (see TestBiomeSeedChangesWithGroundFields) to the three
// fields added for this feature — binary.Write silently dropping a field is
// exactly the bug that already bit this function once, and MossScatter is a
// bool (a new type in that struct), so it's worth pinning.
func TestBiomeSeedChangesWithSlopeFields(t *testing.T) {
	base := BiomeSector{ID: "s0", Brush: BiomeBrush{Kind: BiomeMoss}}

	scat := base
	scat.Brush.MossScatter = true
	if biomeSeed(&base) == biomeSeed(&scat) {
		t.Error("different MossScatter should produce a different seed")
	}

	minS := base
	minS.Brush.MinSlopeAngle = 20
	if biomeSeed(&base) == biomeSeed(&minS) {
		t.Error("different MinSlopeAngle should produce a different seed")
	}

	maxS := base
	maxS.Brush.MaxSlopeAngle = 70
	if biomeSeed(&base) == biomeSeed(&maxS) {
		t.Error("different MaxSlopeAngle should produce a different seed")
	}
}
