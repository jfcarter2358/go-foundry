// TestBiomeFollowsDisplacement pins which kinds conform to (and are
// slope-gated by) a covering face's procedural displacement, versus the ones
// deliberately left on the flat structural floor.
func TestBiomeFollowsDisplacement(t *testing.T) {
	for _, k := range []int32{BiomeGrass, BiomeSand, BiomeRock, BiomeMoss} {
		if !biomeFollowsDisplacement(k) {
			t.Errorf("kind %d should follow displacement", k)
		}
	}
	for _, k := range []int32{BiomeWildflower, BiomeCattail, BiomeWater} {
		if biomeFollowsDisplacement(k) {
			t.Errorf("kind %d should not follow displacement", k)
		}
	}
}

// TestMossScatterGating checks Moss is structurally a scatter kind (so
// Density/Range mean something for it) but only actually issues a draw call
// when its own MossScatter toggle is on — while every other scatter kind
// scatters unconditionally.
func TestMossScatterGating(t *testing.T) {
	if !isScatterKind(BiomeMoss) {
		t.Fatal("Moss should be a scatter-capable kind")
	}

	off := BiomeBrush{Kind: BiomeMoss, MossScatter: false}
	if off.Scatters() {
		t.Error("Moss with MossScatter=false should not scatter (ground patch only)")
	}
	on := BiomeBrush{Kind: BiomeMoss, MossScatter: true}
	if !on.Scatters() {
		t.Error("Moss with MossScatter=true should scatter")
	}

	// MossScatter must not leak into any other kind's decision.
	for _, k := range []int32{BiomeGrass, BiomeRock, BiomeWildflower, BiomeCattail} {
		if b := (BiomeBrush{Kind: k}); !b.Scatters() {
			t.Errorf("kind %d should scatter regardless of MossScatter", k)
		}
	}
	for _, k := range []int32{BiomeSand, BiomeWater} {
		if b := (BiomeBrush{Kind: k, MossScatter: true}); b.Scatters() {
			t.Errorf("kind %d should never scatter even with MossScatter set", k)
		}
	}
}

// TestDefaultMossBrush checks the new kind gets a complete brush like every
// other one — a positive Range (so the renderer's clamp doesn't fall back),
// scatter off by default (ground patch is the default look), and a slope
// ceiling actually set.
func TestDefaultMossBrush(t *testing.T) {
	b := defaultBiomeBrush(BiomeMoss)
	if b.Kind != BiomeMoss {
		t.Fatalf("Kind = %d, want BiomeMoss", b.Kind)
	}
	if b.Range <= 0 {
		t.Error("default Moss brush should have a positive Range")
	}
	if b.MossScatter {
		t.Error("default Moss brush should start ground-patch-only (MossScatter off)")
	}
	// Slope range is left unset (0/0 = the full range) so a fresh sector isn't
	// silently restricted — see TestResolvedSlopeDefaultsGateNothing.
	if b.MinSlopeAngle != 0 || b.MaxSlopeAngle != 0 {
		t.Errorf("default Moss brush should leave the slope range unset, got %v..%v", b.MinSlopeAngle, b.MaxSlopeAngle)
	}
}

