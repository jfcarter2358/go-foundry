package editor

// editor_yaml_docs_gen_test.go — keeps editor_yaml_docs_gen.go in step with the
// level schema's comments.
//
// The YAML editor's completion list and hover show each key's documentation,
// and the only place that documentation exists is the comment on the Go field
// behind the key. Comments are gone by run time, so they are read here, from
// the source, and written into a table the editor compiles in. This test is the
// generator as well as the guard: it fails when the table is stale, and
//
//	FOUNDRY_UPDATE_YAML_DOCS=1 go test ./internal/editor -run TestYAMLFieldDocsUpToDate
//
// rewrites it.

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"reflect"
	"regexp"
	"sort"
	"strings"
	"testing"
)

const yamlDocsGenFile = "editor_yaml_docs_gen.go"

func TestYAMLFieldDocsUpToDate(t *testing.T) {
	want, err := yamlGenerateDocs()
	if err != nil {
		t.Fatal(err)
	}
	if os.Getenv("FOUNDRY_UPDATE_YAML_DOCS") != "" {
		if err := os.WriteFile(yamlDocsGenFile, want, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	have, err := os.ReadFile(yamlDocsGenFile)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(have, want) {
		t.Fatalf("%s is out of date with the level schema's comments; regenerate it with\n"+
			"  FOUNDRY_UPDATE_YAML_DOCS=1 go test ./internal/editor -run TestYAMLFieldDocsUpToDate",
			yamlDocsGenFile)
	}
}

// yamlReachableStructs is every named struct a level file can reach from
// RawLevel, and every one game.yaml can reach from game.Manifest.
func yamlReachableStructs() []reflect.Type {
	seen := map[reflect.Type]bool{}
	var out []reflect.Type
	var visit func(reflect.Type)
	visit = func(t reflect.Type) {
		switch t.Kind() {
		case reflect.Pointer, reflect.Slice, reflect.Array, reflect.Map:
			visit(t.Elem())
		case reflect.Struct:
			if seen[t] || t.Name() == "" {
				return
			}
			seen[t] = true
			out = append(out, t)
			for i := 0; i < t.NumField(); i++ {
				if f := t.Field(i); f.PkgPath == "" || f.Anonymous {
					visit(f.Type)
				}
			}
		}
	}
	visit(yamlRootType)
	visit(yamlGameRootType)
	return out
}

// yamlEnumRe matches the `a (default) | b | c` convention.
var yamlEnumRe = regexp.MustCompile(`^\s*[A-Za-z0-9_.-]+(\s*\(default\))?(\s*\|\s*([A-Za-z0-9_.-]+(\s*\(default\))?|\.\.\.))+\s*$`)

// yamlGenerateDocs builds the table's source.
func yamlGenerateDocs() ([]byte, error) {
	types := yamlReachableStructs()
	// The packages to read, by import path.
	pkgs := map[string]bool{}
	for _, t := range types {
		pkgs[t.PkgPath()] = true
	}
	// field docs keyed "pkg.Type.GoField"
	type fieldDoc struct{ doc, comment string }
	docs := map[string]fieldDoc{}
	for pkg := range pkgs {
		dir, ok := strings.CutPrefix(pkg, "foundry/")
		if !ok {
			continue
		}
		dir = filepath.Join("..", "..", dir)
		files, err := filepath.Glob(filepath.Join(dir, "*.go"))
		if err != nil {
			return nil, err
		}
		short := pkg[strings.LastIndex(pkg, "/")+1:]
		fset := token.NewFileSet()
		for _, path := range files {
			if strings.HasSuffix(path, "_test.go") {
				continue
			}
			f, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
			if err != nil {
				return nil, err
			}
			ast.Inspect(f, func(n ast.Node) bool {
				ts, ok := n.(*ast.TypeSpec)
				if !ok {
					return true
				}
				st, ok := ts.Type.(*ast.StructType)
				if !ok {
					return true
				}
				for _, fld := range st.Fields.List {
					var d, c string
					if fld.Doc != nil {
						d = fld.Doc.Text()
					}
					if fld.Comment != nil {
						c = fld.Comment.Text()
					}
					for _, name := range fld.Names {
						docs[short+"."+ts.Name.Name+"."+name.Name] = fieldDoc{d, c}
					}
				}
				return true
			})
		}
	}

	fieldDocs := map[string]string{}
	enums := map[string][]string{}
	for _, t := range types {
		for i := 0; i < t.NumField(); i++ {
			sf := t.Field(i)
			if sf.PkgPath != "" || sf.Anonymous {
				continue
			}
			tag := sf.Tag.Get("yaml")
			name, opts, _ := strings.Cut(tag, ",")
			if tag == "-" || strings.Contains(","+opts+",", ",inline,") {
				continue
			}
			if name == "" {
				name = strings.ToLower(sf.Name)
			}
			fd, ok := docs[t.String()+"."+sf.Name]
			if !ok {
				continue
			}
			key := t.String() + "." + name
			text := yamlCleanDoc(fd.doc)
			if c := yamlCleanDoc(fd.comment); c != "" {
				if yamlEnumRe.MatchString(c) {
					enums[key] = yamlEnumValues(c)
				}
				if text == "" {
					text = c
				} else {
					text += "\n" + c
				}
			}
			if text != "" {
				fieldDocs[key] = text
			}
		}
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by TestYAMLFieldDocsUpToDate from the level schema's comments. DO NOT EDIT.\n")
	b.WriteString("//\n// Regenerate with\n//\n//\tFOUNDRY_UPDATE_YAML_DOCS=1 go test ./internal/editor -run TestYAMLFieldDocsUpToDate\n\n")
	b.WriteString("package editor\n\n")
	b.WriteString("// yamlFieldDocs is each level-file key's documentation, keyed \"pkg.Type.key\".\n")
	b.WriteString("var yamlFieldDocs = map[string]string{\n")
	for _, k := range yamlSortedKeys(fieldDocs) {
		fmt.Fprintf(&b, "%q: %q,\n", k, fieldDocs[k])
	}
	b.WriteString("}\n\n")
	b.WriteString("// yamlFieldEnums is the values a string key's comment lists, keyed as above.\n")
	b.WriteString("var yamlFieldEnums = map[string][]string{\n")
	for _, k := range yamlSortedKeys(enums) {
		fmt.Fprintf(&b, "%q: {", k)
		for i, v := range enums[k] {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%q", v)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

func yamlSortedKeys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// yamlCleanDoc turns a comment into the text a tooltip shows: paragraphs kept,
// the lines inside each rejoined so the tooltip can wrap them itself, and cut
// after the second paragraph — the rest of a long comment is usually the
// history of why, which belongs in the source rather than in a popup.
func yamlCleanDoc(s string) string {
	s = strings.TrimSpace(s)
	if s == "" {
		return ""
	}
	paras := strings.Split(s, "\n\n")
	if len(paras) > 2 {
		paras = paras[:2]
	}
	for i, p := range paras {
		paras[i] = strings.Join(strings.Fields(p), " ")
	}
	return strings.Join(paras, "\n\n")
}

// yamlEnumValues pulls the options out of an `a (default) | b | c` comment.
func yamlEnumValues(c string) []string {
	var out []string
	for _, part := range strings.Split(c, "|") {
		v := strings.TrimSpace(strings.TrimSuffix(strings.TrimSpace(part), "(default)"))
		if v == "" || v == "..." {
			continue
		}
		out = append(out, v)
	}
	return out
}
