package synth

// recipes_winds.go — brass and woodwinds (recipes 103-110), all looped.
//
// The thing that makes brass sound like brass rather than a filtered saw is
// that its spectrum depends on how hard it is blown: the upper harmonics
// grow faster than the fundamental as level rises (Risset's observation).
// harmonicVoice takes a level curve and lets each harmonic follow a
// different power of it, so the attack blooms from dark to bright exactly
// as a real one does. Woodwinds are simpler — a fixed spectrum plus the
// breath noise and the "chiff" of the tone starting, which is what sells
// them.

import "math"

func windRecipes() []Recipe {
	w := func(name, base, desc string, tags []string, ps []Param, body func(*ctx) *out) Recipe {
		return rec(name, "winds", base, desc, tags, ps, body)
	}
	return []Recipe{
		w("brass_section", "C-4", "Brass section: saws whose filter opens on the attack", []string{"brass", "section", "stereo"}, []Param{
			par("bright", 0.6, 0, 1, "filter opening"),
			par("detune", 7, 0, 20, "section spread in cents"),
			par("attack", 0.06, 0.01, 0.3, "seconds"),
		}, brassSection),
		w("trumpet", "C-4", "Trumpet: brightness tied to how hard it is blown", []string{"brass", "trumpet"}, []Param{
			par("level", 0.85, 0.3, 1, "how hard it is blown"),
			par("bright", 0.6, 0, 1, "level-to-brightness coupling"),
			par("attack", 0.05, 0.01, 0.3, "seconds"),
		}, trumpet),
		w("french_horn", "C-3", "French horn: dark and round", []string{"brass", "horn", "orchestral"}, []Param{
			par("level", 0.8, 0.3, 1, "how hard it is blown"),
			par("attack", 0.09, 0.02, 0.4, "seconds"),
		}, frenchHorn),
		w("trombone", "C-3", "Trombone: brassy with a lip buzz", []string{"brass", "trombone"}, []Param{
			par("level", 0.85, 0.3, 1, "how hard it is blown"),
			par("buzz", 0.3, 0, 1, "lip buzz"),
			par("attack", 0.06, 0.01, 0.3, "seconds"),
		}, trombone),
		w("flute", "C-5", "Flute: pure tone, breath and chiff", []string{"woodwind", "flute"}, []Param{
			par("breath", 0.3, 0, 1, "breath noise"),
			par("chiff", 0.4, 0, 1, "attack chiff"),
		}, flute),
		w("clarinet", "C-4", "Clarinet: hollow odd harmonics", []string{"woodwind", "clarinet"}, []Param{
			par("tone", 2500, 800, 6000, "lowpass in Hz"),
			par("breath", 0.15, 0, 1, "breath noise"),
		}, clarinet),
		w("oboe", "C-4", "Oboe: narrow, nasal reed", []string{"woodwind", "oboe", "reed"}, []Param{
			par("width", 0.1, 0.04, 0.3, "pulse width"),
			par("nasal", 0.6, 0, 1, "formant strength"),
		}, oboe),
		w("pan_flute", "C-5", "Pan flute: breathy stopped pipe with a strong chiff", []string{"woodwind", "panflute", "breathy"}, []Param{
			par("breath", 0.5, 0, 1, "breath noise"),
			par("chiff", 0.6, 0, 1, "attack chiff"),
		}, panFlute),
	}
}

// harmonicVoice renders a harmonic tone: fundamental f(t), and harmonics
// 1..maxH at amp(h, A) where A = level(t). Harmonics are generated by complex powers
// of the fundamental's phasor, so they stay locked to it through any bend.
func harmonicVoice(c *ctx, n, maxH int, f, level func(t float64) float64, amp func(h int, A float64) float64) []float64 {
	var ph float64
	lim := 0.45 * c.sr
	return render(n, func(i int) float64 {
		t := c.t(i)
		fi := f(t)
		A := level(t)
		th := 2 * math.Pi * ph
		cr, ci := math.Cos(th), math.Sin(th)
		re, im := cr, ci
		var v float64
		for h := 1; h <= maxH && float64(h)*fi < lim; h++ {
			if a := amp(h, A); a != 0 {
				v += a * im
			}
			re, im = re*cr-im*ci, re*ci+im*cr
		}
		ph += fi / c.sr
		ph -= math.Floor(ph)
		return v
	})
}

// scoop is a brass player's lip settling into the note: a few cents flat at
// the start, exactly in tune by `dur`.
func scoop(f, cents, dur float64) func(t float64) float64 {
	return func(t float64) float64 { return f * math.Pow(2, -cents*(1-smooth(t/dur))/1200) }
}

func brassSection(c *ctx) *out {
	bright, d, att := c.v("bright"), c.v("detune"), c.v("attack")
	p := c.plan(att+0.35, 2)
	n := p.frames()
	// The filter overshoots as the section bites, then settles.
	open := func(t float64) float64 {
		if t < att {
			return 1.25 * smooth(t/att)
		}
		return 1 + 0.25*(1-smooth((t-att)/0.2))
	}
	side := func(r *rng, skew float64) []float64 {
		x := make([]float64, n)
		for k, f := range spreadFreqs(p, 4, d, skew) {
			var o osc
			o.ph = r.float()
			sc := scoop(f, 25+10*float64(k), 0.08)
			for i := range x {
				x[i] += o.saw(sc(c.t(i)) / c.sr)
			}
		}
		var lp svf
		for i := range x {
			t := c.t(i)
			lp.set(350+3500*bright*open(t), 0.8, c.sr)
			y, _, _ := lp.tick(x[i] * 0.4)
			x[i] = math.Tanh(1.3*y) * rise(t, att)
		}
		return x
	}
	return stereo(side(c.rng.fork(), 0.2), side(c.rng.fork(), -0.2)).looped(p)
}

func trumpet(c *ctx) *out {
	lvl, bright, att := c.v("level"), c.v("bright"), c.v("attack")
	p := c.plan(att+0.3, 1.5)
	base := []float64{0.55, 0.85, 1, 0.95, 0.8, 0.62, 0.48, 0.36, 0.26, 0.19, 0.13, 0.09, 0.06, 0.04, 0.03, 0.02}
	x := harmonicVoice(c, p.frames(), 16, scoop(p.f0, 20, 0.05),
		func(t float64) float64 { return ads(t, att, 0.15, lvl) },
		func(h int, A float64) float64 {
			if h > len(base) {
				return 0
			}
			return base[h-1] * math.Pow(A, 1+0.35*float64(h-1)*bright)
		})
	return mono(x).looped(p)
}

func frenchHorn(c *ctx) *out {
	lvl, att := c.v("level"), c.v("attack")
	p := c.plan(att+0.35, 2)
	x := harmonicVoice(c, p.frames(), 28, scoop(p.f0, 15, 0.08),
		func(t float64) float64 { return ads(t, att, 0.2, lvl) },
		func(h int, A float64) float64 {
			fh := float64(h) * p.f0
			return math.Pow(0.72, float64(h-1)) / (1 + math.Pow(fh/1300, 2)) * math.Pow(A, 1+0.18*float64(h-1))
		})
	lpBuf(x, 2500, c.sr, 1)
	return mono(x).looped(p)
}

func trombone(c *ctx) *out {
	lvl, buzz, att := c.v("level"), c.v("buzz"), c.v("attack")
	p := c.plan(att+0.3, 2)
	n := p.frames()
	x := harmonicVoice(c, n, 60, scoop(p.f0, 25, 0.06),
		func(t float64) float64 { return ads(t, att, 0.15, lvl) },
		func(h int, A float64) float64 {
			fh := float64(h) * p.f0
			l := math.Log(fh / 750)
			return (math.Exp(-l*l/0.9) + 0.25/float64(h)) * math.Pow(A, 1+0.25*float64(h-1))
		})
	norm1(x)
	// The lips buzz once a cycle: noise gated at the pitch.
	var ph float64
	bz := render(n, func(i int) float64 {
		ph += p.f0 / c.sr
		ph -= math.Floor(ph)
		g := 0.0
		if ph < 0.2 {
			g = 1
		}
		return g * c.rng.white() * ads(c.t(i), att, 0.15, lvl)
	})
	lpBuf(bz, 3000, c.sr, 1)
	addTo(x, norm1(bz), 0.08*buzz)
	return mono(x).looped(p).fade(0.04)
}

// windNoise is a woodwind's breath and chiff layered onto a tone.
func windNoise(c *ctx, x []float64, f, breath, chiff, chiffAt, att float64) {
	n := len(x)
	pitched := breathAt(c.rng, n, c.sr, f, 15)
	air := breathAt(c.rng, n, c.sr, 2500, 0.5)
	ch := noiseHit(c.rng, n, c.sr, func(y []float64) {
		var bp svf
		bp.set(chiffAt, 1.2, c.sr)
		for i, v := range y {
			_, b, _ := bp.tick(v)
			y[i] = b
		}
	}, func(t float64) float64 { return rise(t, 0.008) * math.Exp(-t/0.035) })
	for i := range x {
		r := rise(c.t(i), att)
		x[i] = x[i]*r + breath*r*(0.3*pitched[i]+0.08*air[i]) + 0.5*chiff*ch[i]
	}
}

func flute(c *ctx) *out {
	breath, chiff := c.v("breath"), c.v("chiff")
	p := c.plan(0.35, 1.5)
	amps := []float64{1, 0.22, 0.09, 0.04, 0.02}
	x := harmonicVoice(c, p.frames(), 40, func(float64) float64 { return p.f0 }, func(float64) float64 { return 1 },
		func(h int, _ float64) float64 {
			if h > len(amps) {
				return 0
			}
			return amps[h-1]
		})
	windNoise(c, x, p.f0, breath, chiff, 4000, 0.07)
	return mono(x).looped(p).fade(0.05)
}

func clarinet(c *ctx) *out {
	tone, breath := c.v("tone"), c.v("breath")
	p := c.plan(0.3, 1.5)
	x := harmonicVoice(c, p.frames(), 40, func(float64) float64 { return p.f0 }, func(float64) float64 { return 1 },
		func(h int, _ float64) float64 {
			if h%2 == 0 {
				return 0.03 / float64(h)
			}
			return 1 / math.Pow(float64(h), 0.9)
		})
	lpBuf(x, tone, c.sr, 1)
	windNoise(c, x, p.f0, breath, 0.15, 2000, 0.04)
	return mono(x).looped(p).fade(0.05)
}

func oboe(c *ctx) *out {
	w, nasal := c.v("width"), c.v("nasal")
	p := c.plan(0.3, 1.5)
	var o osc
	x := render(p.frames(), func(i int) float64 { return o.pulse(p.f0/c.sr, w) })
	eq(x, bqPeak(1100, 2, 8*nasal, c.sr), bqPeak(2900, 3, 5*nasal, c.sr),
		bqLowpass(6000, 0.7, c.sr), bqHighpass(300, 0.7, c.sr))
	norm1(x)
	windNoise(c, x, p.f0, 0.08, 0.1, 2500, 0.04)
	return mono(x).looped(p).fade(0.05)
}

func panFlute(c *ctx) *out {
	breath, chiff := c.v("breath"), c.v("chiff")
	p := c.plan(0.4, 1.5)
	amps := []float64{1, 0.03, 0.12, 0, 0.04}
	n := p.frames()
	x := harmonicVoice(c, n, 5, func(float64) float64 { return p.f0 }, func(float64) float64 { return 1 },
		func(h int, _ float64) float64 {
			if h > len(amps) {
				return 0
			}
			return amps[h-1]
		})
	// Overblow: the second harmonic speaks for an instant as the breath hits.
	ob := make([]float64, n)
	addPartials(ob, c.sr, []partial{{f: 2 * p.f0, amp: 0.3 * chiff, t60: 0.12}})
	addTo(x, ob, 1)
	windNoise(c, x, p.f0, breath*1.6, chiff*1.3, 3000, 0.05)
	return mono(x).looped(p).fade(0.05)
}
